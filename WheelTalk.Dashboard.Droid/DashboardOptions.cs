using WheelTalk.Core.Battery;

namespace WheelTalk.Dashboard.Droid;

/// <summary>
/// Ручки, которые крутятся на устройстве, пока идёт реплей. Смысл именно в этом: выбирается не
/// один вариант панели, а набор приёмов, а набор нельзя перебрать пересборкой — каждая гипотеза
/// стоила бы цикла сборки и установки.
/// <para>
/// Один экземпляр на всё приложение; после изменения зовётся <see cref="Notify"/>, и панель
/// перерисовывается. Событие, а не привязки: панель и так перерисовывается по каждому кадру
/// (<c>PostInvalidateOnAnimation</c>), система привязок здесь ничего не добавляет.
/// </para>
/// <para>
/// Портировано из <c>WheelTalk.Dashboard/DashboardOptions.cs</c> без изменений — MAUI-типов в
/// этом файле не было изначально, поменялось только пространство имён.
/// </para>
/// </summary>
public sealed class DashboardOptions
{
    public event Action? Changed;

    /// <summary>
    /// Начало шкалы ШИМ. 50, а не 0: ниже смотреть не на что, а линейная шкала 0…100 отдала бы
    /// половину длины диапазону, в котором ничего не происходит.
    /// </summary>
    public double ScaleMin { get; set; } = 50;

    public double ScaleMax { get; set; } = 100;

    /// <summary>
    /// Пороги ШИМ и толщина полосы тревоги — одно имя вместо трёх пар «свойство + источник» (план
    /// 19 Б3, продолжение плана 14 Б1.1). Приложение подставляет реализацию поверх живого
    /// <c>AlertOptions</c> при сборке DI — правка страницы «Предупреждения» видна панели сразу,
    /// зеркалировать на каждом кадре не нужно; стенд крутит умолчание (<see cref="DashboardThresholds"/>)
    /// своими ручками.
    /// </summary>
    public IDashboardThresholds Thresholds { get; set; } = new DashboardThresholds();

    /// <summary>Выше этого на шкале идёт косая штриховка («barber pole» авиационных лент).</summary>
    public double BarberPolePwm { get; set; } = 95;

    /// <summary>Личный предел райдера — бирка на шкале. Ноль убирает её.</summary>
    public double PersonalLimit { get; set; } = 88;

    /// <summary>
    /// На сколько секунд вперёд смотрит вектор тренда. В авиации шесть, у нас динамика другая:
    /// два — то, что надо проверить глазами, а не вычислить.
    /// </summary>
    public double TrendSeconds { get; set; } = 2;

    public bool ShowTrend { get; set; } = true;
    public bool ShowBug { get; set; } = true;
    public bool ShowBarberPole { get; set; } = true;

    /// <summary>Шаг дискретной шкалы (дуга варианта B, линейка сегментов), процентов ШИМ.</summary>
    public double SegmentPercent { get; set; } = 2;

    /// <summary>
    /// Выше этой скорости десятые не показываются, а освободившееся место идёт в кегль. Ноль —
    /// показывать всегда.
    /// </summary>
    public double HideTenthsAbove { get; set; } = 30;

    /// <summary>
    /// Выше этой скорости справочные значения уходят с экрана, а цифра скорости занимает их место.
    /// Решение спорное и потому отдельной ручкой: выше тридцати смотреть некогда, и всё, что не
    /// ШИМ и не скорость, отнимает у них внимание — но проверять это надо глазами, а не доводами.
    /// </summary>
    public double HideExtrasAbove { get; set; }

    /// <summary>Наклон панели, градусов — режим для телефона на запястье.</summary>
    public double Tilt { get; set; }

    /// <summary>
    /// Чем ближе ШИМ к пределу, тем больше места он забирает у скорости. Идея владельца, и её
    /// цена — меняющаяся геометрия ровно в тот момент, когда скорость нужнее всего; поэтому
    /// переключатель, а не константа.
    /// </summary>
    public bool PwmCrowdsOutSpeed { get; set; } = true;

    /// <summary>
    /// Постоянная времени сглаживания ШИМ, секунд. Ноль — сырое значение. Сглаживание врёт про
    /// скачки, а именно скачок и важен, поэтому это ручка, а не константа.
    /// </summary>
    public double SmoothingSeconds { get; set; } = 0.15;

    /// <summary>Тревожная рамка плана 4 поверх панели. В варианте с заливкой она может мешать.</summary>
    public bool ShowAlertBorder { get; set; } = true;

    /// <summary>
    /// Частота моргания рамки, Гц. WCAG 2.3.1 не допускает больше трёх вспышек в секунду (период
    /// не короче 333 мс) — дефолт стоит ровно на этой границе. До правки 29.07.2026 в приложении
    /// было выставлено 4 — «посередине допустимого» по MIL-STD-1472 для аварийного сигнала, но
    /// выше порога WCAG; решение владельца (dashboard-feedback.md «Решения 29.07.2026» → «Мигание
    /// и WCAG 2.3.1») — держаться доступности, а не военного стандарта. Ручка остаётся ручкой:
    /// библиотека верхнюю границу не навязывает, значение выше трёх можно выставить в
    /// «Отображении» — экран настроек в эту работу не входит.
    /// </summary>
    public double BlinkHz { get; set; } = 3;

    /// <summary>Верх шкалы ШИМ. 200 %: шкала не должна обрываться там, где значение ещё бывает.</summary>
    public double PwmScaleTop { get; set; } = 200;

    /// <summary>
    /// Сколько точек экрана приходится на процент ШИМ. Задаёт и видимый кусок шкалы, и то, насколько
    /// заметно она едет: чем плотнее, тем больше диапазона видно и тем меньше ход при том же
    /// изменении.
    /// </summary>
    public double PwmDpPerUnit { get; set; } = 12;

    /// <summary>
    /// Сколько времени лента идёт к новому значению, секунд, но не меньше интервала между кадрами
    /// телеметрии: сам интервал лента измеряет и берёт его, пока эта величина меньше. Сглаживается
    /// только разметка — цифра в окне остаётся сырой. Ноль отключает ход: шкала прыгает на новое
    /// значение, как только оно пришло.
    /// </summary>
    public double TapeSmoothSeconds { get; set; } = 0.02;

    /// <summary>
    /// Доля ширины экрана на одну ленту, процентов. Ручка, а не константа: расширение лент —
    /// замечание прогона 4, но оно перекраивает центр (кегль скорости подбирается под его ширину),
    /// поэтому проверяется на стенде глазами, а не выбирается расчётом.
    /// </summary>
    public double TapeShare { get; set; } = 28;

    /// <summary>
    /// Выше этой скорости имя колеса с экрана уходит, км/ч. Оно нужно на стоянке — поймать
    /// подключение к чужому колесу, — а на ходу это лишний текст поверх приборов. Ноль — показывать
    /// всегда.
    /// </summary>
    public double ShowNameBelow { get; set; } = 10;

    /// <summary>
    /// Ниже этого ШИМ шкала серая. Диапазон остаётся на месте — обрыв разметки на полпути читается
    /// как поломка прибора, — но цветом сказано, что смотреть там не на что.
    /// </summary>
    public double PwmGreyBelow { get; set; } = 50;

    /// <summary>
    /// Напряжение пакета, ниже которого шкала напряжения жёлтая, вольт. **Абсолютное**, то есть
    /// зона стоит на шкале неподвижно.
    /// <para>
    /// До 01.08.2026 порог отсчитывался от холостого напряжения (`просадка ≥ 3 В`), а холостое
    /// приложение переопределяло на каждом выбеге — и зоны ехали по шкале вслед за садящимся паком,
    /// шагая на каждом светофоре. Решение владельца: от холостого напряжения на шкале отказаться,
    /// пороги сделать абсолютными. Довод тот же, которым обоснован неподвижный масштаб: прибор с
    /// ползающей разметкой перестаёт быть сравнимым сам с собой.
    /// </para>
    /// <para>
    /// В вольтах пакета, а не на банку: на банку пришлось бы знать число банок, а колесо его не
    /// сообщает. **Ноль выключает зону, и это умолчание** — по той же причине, что у
    /// <see cref="EmptyVolts"/>: абсолютный порог зависит от пакета целиком, угадать его не из чего,
    /// а угаданный неверно закрасил бы ленту на всю поездку. Задаётся в настройках, у каждого колеса
    /// свой слой.
    /// </para>
    /// </summary>
    public double WarnVolts { get; set; }

    /// <summary>Напряжение пакета, ниже которого шкала красная, вольт. Ноль выключает зону.</summary>
    public double DangerVolts { get; set; }

    /// <summary>
    /// Абсолютный пол: напряжение пакета, ниже которого пак кончился, а не просел. Живёт на той же
    /// оси четвёртой зоной — это не второй прибор, а вторая разметка: относительная работает каждый
    /// разгон, абсолютная всплывает раз в поездку, в конце.
    /// <para>
    /// Ноль выключает зону, и это умолчание. Пол зависит от размера пакета целиком, угадать его не
    /// из чего, а угаданный неверно закрасил бы красным всю ленту на всю поездку — то есть отключил
    /// бы прибор. Пусть лучше молчит, пока не сказали.
    /// </para>
    /// </summary>
    public double EmptyVolts { get; set; }

    /// <summary>
    /// Видимый кусок шкалы напряжения, вольт. Десять — тот масштаб, на котором просадка в пару
    /// вольт видна как заметный ход, а не как дрожание у окна.
    /// </summary>
    public double SagWindowVolts { get; set; } = 10;

    /// <summary>
    /// Видимый кусок <b>ячейковой</b> шкалы, вольт на банку. Своё число, а не пересчитанное из
    /// пакетного: у ленты на ячейку своя жизнь (план 27 §27.4). Полвольта — примерно тот же ход,
    /// что даёт десять вольт на двадцатибаночном паке.
    /// </summary>
    public double SagWindowCellVolts { get; set; } = 0.5;

    /// <summary>
    /// Что показывает левая шкала. Заводское — напряжение пакета, и само оно не переключается
    /// никогда: пункт выбирает человек (план 27 §27.4). Режим, которому нечем считать (нет BMS,
    /// не задан ряд), мягко возвращается к пакету — это не ошибка, а обычный день.
    /// </summary>
    public VoltageScaleMode VoltageScale { get; set; } = VoltageScaleMode.Pack;

    /// <summary>
    /// Порог «жёлтой» зоны в вольтах на ячейку. В отличие от пакетного, предзаполнен и работает из
    /// коробки: 3,5 В — это 3,5 В и на 20S, и на 60S, угадывать тут нечего (план 27 §27.4). Ноль
    /// выключает зону, как и у пакетного порога.
    /// </summary>
    public double WarnCellVolts { get; set; } = 3.5;

    /// <summary>Порог красной зоны, вольт на ячейку. Ноль выключает.</summary>
    public double DangerCellVolts { get; set; } = 3.3;

    /// <summary>Пол шкалы, вольт на ячейку: ниже — пак кончился, а не просел. Ноль выключает.</summary>
    public double EmptyCellVolts { get; set; } = 3.2;

    /// <summary>
    /// Растягивать шкалу напряжения под размах поездки, беря <see cref="SagWindowVolts"/> за
    /// нижнюю границу. Выключено по умолчанию, и это не осторожность: просадка — единицы вольт,
    /// разряд за поездку — десятки, и через полчаса автомасштаб определяется разрядом, а просадка
    /// на нём снова становится дрожанием. Кому важнее видеть весь разряд разом — включает.
    /// </summary>
    public bool SagAutoScale { get; set; }

    /// <summary>
    /// Скорость, на которой кольцо вокруг цифры заполняется целиком. Не предел и не тревога —
    /// просто масштаб, чтобы у цифры была форма, читаемая периферией.
    /// </summary>
    public double ReferenceSpeed { get; set; } = 60;

    public DashboardPalette Palette { get; set; } = DashboardPalette.Wong;

    public void Notify() => Changed?.Invoke();

    /// <summary>Доля шкалы, которую занимает значение — 0 в начале шкалы, 1 в конце.</summary>
    public double Fraction(double pwm)
    {
        double span = ScaleMax - ScaleMin;
        return span <= 0 ? 0 : Math.Clamp((pwm - ScaleMin) / span, 0, 1);
    }

    /// <summary>Скорость так, как её показывает панель: с десятыми или без, по порогу выше.</summary>
    public string FormatSpeed(double speedKmh) =>
        HideTenthsAbove > 0 && speedKmh >= HideTenthsAbove
            ? speedKmh.ToString("F0")
            : speedKmh.ToString("F1");
}
