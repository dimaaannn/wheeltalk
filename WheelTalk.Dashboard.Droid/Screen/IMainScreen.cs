using Android.Views;

namespace WheelTalk.Dashboard.Droid.Screen;

/// <summary>
/// Контракт основного экрана (план 17 §2, план 23 §2.1). Экран умеет ровно две вещи: принять
/// посчитанное состояние кадра (<see cref="MainScreenFrame"/>) и сообщить о намерении
/// (<see cref="MainScreenIntent"/>). Всё остальное — не его дело.
/// <para>
/// <b>Чего экран не делает никогда:</b> не ходит в <c>WheelSession</c>, <c>RideRecorder</c> и
/// контейнер служб, не подключается и не отключается, не запускает сервис, не просит разрешений,
/// не пишет настройки и не открывает Activity сам. Иначе каждый новый экран заведёт свои связи с
/// ядром — ровно то, от чего уходим.
/// </para>
/// <para>
/// <b>Что остаётся хозяину</b> (<c>MainActivity</c>): жизненный цикл, подключение и погоня, сервис,
/// разрешения, замок и яркость, шторка, полоса тревоги, инсеты и кадровый цикл
/// (<see cref="MainScreenDriver"/>).
/// </para>
/// </summary>
public interface IMainScreen
{
    /// <summary>Сам экран как элемент разметки: его кладёт в рамку <see cref="MainScreenView"/>.</summary>
    View View { get; }

    /// <summary>
    /// Куда уходят намерения. Ставит хозяин — он один знает, чем намерение исполнить.
    /// </summary>
    Action<MainScreenIntent>? OnIntent { get; set; }

    /// <summary>Очередной кадр. Зовётся с частотой отрисовки, поэтому дешёвый и без выделений.</summary>
    void Show(MainScreenFrame frame);

    /// <summary>
    /// Касание по экрану, в координатах окна: экран сам решает, попало ли оно во что-то значимое, и
    /// сам переводит координаты в свои. Хозяин ловит жест (у него уже есть
    /// <c>DispatchTouchEvent</c>) и не знает, из чего экран собран.
    /// </summary>
    void Tap(float windowX, float windowY);

    /// <summary>
    /// Кнопка «назад». <c>true</c> — экран её взял себе (закрыл своё временное состояние), и хозяину
    /// делать нечего; <c>false</c> — пусть решает хозяин.
    /// <para>
    /// По умолчанию не берёт: экран, у которого нечего закрывать, не должен об этом писать. Взял
    /// пока один — плитки в режиме правки, где «назад» значит «не сохранять».
    /// </para>
    /// </summary>
    bool Back() => false;

    /// <summary>
    /// Колесо сменилось — забудь, что накопил про прежнее. Зовёт хозяин по событию сессии
    /// (план 29 §29.1); кадры нового колеса придут уже после.
    /// <para>
    /// По умолчанию не делает ничего: экрану, который ничего не копит, забывать нечего. Копит пока
    /// один — плитки, где крайние значения означают «на что колесо оказалось способно», и максимум
    /// прежнего колеса на плитке нового есть враньё (баг владельца 09.08.2026).
    /// </para>
    /// </summary>
    void WheelChanged() { }
}

/// <summary>
/// Намерение, а не действие: экран говорит, чего хочет райдер, а кто и как это исполнит — забота
/// хозяина. «Показать связь» на подключённом колесе не делает ничего, на реплее пускает запись, в
/// остальных случаях открывает поиск — экрану знать про это нечего.
/// </summary>
public enum MainScreenIntent
{
    /// <summary>Тап по плашке связи — «заняться связью».</summary>
    ShowConnection,

    /// <summary>Тап по точке записи — «показать запись».</summary>
    ShowRecording,

    /// <summary>Тап по галочке снизу — «открыть шторку быстрых команд».</summary>
    ShowSheet,
}
