namespace WheelTalk.Dashboard.Droid.Screen.Tiles;

/// <summary>
/// Черновик раскладки: то, во что её переставили руками. Живёт в памяти процесса — переживает
/// пересборку экрана, но не перезапуск приложения.
/// <para>
/// <b>Хранение в настройке (план 23 §3.4) отложено намеренно.</b> Плитка описывается не тройкой, а
/// четвёркой — у неё будут свойства вида (дополнение владельца 04.08.2026, «число поверх графика»),
/// и формат, заведённый до них, сломался бы первым же свойством. Пока раскладку правят, чтобы
/// пощупать удобство, черновика в памяти хватает.
/// </para>
/// <para>
/// Статика, а не поле экрана, по той же причине, по какой числа вида — свойства: на подгонке экран
/// пересобирают десятками раз, и раскладка, живущая в экране, слетала бы на каждой пересборке.
/// Правка зашитого списка <see cref="TilesLayout.Fixed"/> черновиком закрыта — сбрасывать командой
/// <c>--es layout reset</c>.
/// </para>
/// </summary>
public static class TileLayoutDraft
{
    private static List<MetricTile>? _tiles;

    /// <summary>Раскладка на показ: черновик, если его правили, иначе зашитая.</summary>
    public static IReadOnlyList<MetricTile> Tiles => _tiles ??= [.. TilesLayout.Fixed];

    /// <summary>Запомнить правку. Зовётся с каждым переносом и сменой ширины — их единицы.</summary>
    public static void Keep(IEnumerable<MetricTile> tiles) => _tiles = [.. tiles];

    /// <summary>Забыть правки и вернуться к зашитой раскладке.</summary>
    public static void Reset() => _tiles = null;
}
