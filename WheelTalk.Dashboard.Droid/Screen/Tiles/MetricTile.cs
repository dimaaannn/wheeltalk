using System.Globalization;

namespace WheelTalk.Dashboard.Droid.Screen.Tiles;

/// <summary>
/// Размер плитки в клетках сетки (план 23 §3.3): ширина в колонках, высота в строках. Двенадцать
/// колонок в ряду — доля берётся от них: 3 — четверть, 6 — половина, 12 — весь ряд.
/// <para>
/// <b>Высота — своя мера, а не следствие ширины</b> (решение владельца 04.08.2026 отменено им же
/// 04.08.2026 вечером). Без неё не собрать ряд «половина плюс четыре четвертных в два столбика»: он
/// требует, чтобы рядом с двухстрочной плиткой стояли однострочные.
/// </para>
/// </summary>
public readonly record struct TileSize(int Columns, int Rows);

public static class TileSizes
{
    /// <summary>
    /// Подпись размера — долей ряда: «1/4», «1/2 × 2». Слов здесь нет намеренно: доля и множитель
    /// читаются на любом языке, и переводить их не приходится.
    /// </summary>
    public static string Describe(this TileSize size)
    {
        string width = size.Columns >= TilesLayout.Columns
            ? "1"
            : $"1/{TilesLayout.Columns / size.Columns}";

        return size.Rows == 1 ? width : $"{width} × {size.Rows.ToString(CultureInfo.InvariantCulture)}";
    }
}

/// <summary>
/// Как рисуется плитка. Величина — параметр рисовальщика, а не его вид: ровно то, ради чего заведён
/// <c>MetricCatalogue</c> (план 23 §7 — «тип плитки на каждую величину» запрещён).
/// </summary>
public enum TileKind
{
    /// <summary>Текущее число из живого снимка.</summary>
    Value,

    /// <summary>
    /// Ход величины во времени — единственный вид, которому нужна история (план 23 §3.2). Берётся
    /// она из таблицы телеметрии запросом, а не копится в памяти экрана.
    /// </summary>
    Chart,

    /// <summary>
    /// Крайнее значение за время наблюдения — максимум либо минимум (план 23 §3.2). Истории не
    /// требует вовсе: крайнему значению нужна не запись, а память о двух числах, поэтому плитка
    /// работает и там, где телеметрия не пишется.
    /// </summary>
    Extremum,

    /// <summary>
    /// Дистанция от точки, которую поставил человек (решение владельца 10.08.2026): общий пробег
    /// колеса минус запомненное показание одометра. Одометр здесь — источник, а не то, что видно:
    /// на плитке путь, пройденный с последнего сброса.
    /// <para>
    /// От крайнего значения этот вид отличается <b>отношением к сбросу</b>, и в этом весь смысл:
    /// пик сбрасывается сменой колеса, а дистанция не сбрасывается ничем, кроме руки хозяина, —
    /// ни поездкой, ни перезапуском, ни другим колесом (вернулся — счёт продолжился). Потому её
    /// точка и живёт в хранилище, а не в памяти экрана.
    /// </para>
    /// </summary>
    Trip,

    /// <summary>
    /// Место, оставленное пустым. Не рисует ничего и занимает клетки — этим и держит дырку в
    /// раскладке: укладчик идёт по списку вперёд и в обход занятого не возвращается, поэтому пустое
    /// место остаётся ровно там, где его поставили.
    /// </summary>
    Empty,

    // Chart (график из таблицы телеметрии) и Extremum (максимум/минимум с независимым сбросом)
    // приходят шагами 6 и 7 плана 23. Их здесь нет намеренно: рисовальщик без своих данных — это
    // пустая плитка, а не задел.
}

/// <summary>
/// Одна плитка раскладки: чем рисовать, что рисовать и какого размера. Размер задаётся при создании
/// плитки и переносом не меняется (решение владельца 04.08.2026): перетаскивание двигает плитку, а
/// не подгоняет её под место.
/// </summary>
/// <param name="MetricId">Имя величины из <c>MetricCatalogue</c>. У пустой плитки пусто.</param>
/// <param name="ShowLabel">
/// Показывать ли подпись величины сверху. Выключается затем, что на мелкой плитке строка подписи
/// забирает место у числа, а величина часто узнаётся по нему самому — по разрядам и единице
/// (решение владельца 04.08.2026).
/// </param>
/// <param name="Chart">
/// Свойства вида — пока они есть только у графика (план 23 §3.2, дополнение владельца 04.08.2026).
/// Отдельным членом, а не общим мешком: свойств сегодня три, но лежат они там, где применяются.
/// </param>
/// <param name="Limits">
/// Свои пороги плитки. <c>null</c> — брать их из настроек тревог, как делает панель; заданные здесь
/// старше настроечных и работают для любой величины, а не только для тех двух, у которых пороги в
/// настройках есть.
/// </param>
/// <param name="ShowHeatBar">
/// Показывать ли полоску жара по низу плитки. Своя у каждой плитки — тем же правом, что и пороги
/// (<paramref name="Limits"/>): полоска отвечает «насколько близко к тревоге», и на плитке, где
/// тревоге взяться неоткуда, она лишняя строка внимания. Включена по умолчанию, и старая
/// сохранённая раскладка, где поля нет вовсе, читается именно так.
/// </param>
/// <param name="Decimals">
/// Своё число знаков после запятой. <c>null</c> — умолчание типа величины
/// (<c>MetricRounding</c>), и старая сохранённая раскладка, где поля нет вовсе, читается
/// именно так. Своё нужно затем, что одну и ту же величину человек ставит и крупной плиткой, на
/// которую смотрит, и справочной четвертной: подробность у них разная, а величина одна.
/// </param>
/// <param name="Caption">
/// Своя подпись вместо имени величины (решение владельца 10.08.2026). Пусто — имя величины, как
/// было. Ради неё вид и заведён: две дистанции рядом называются «С последнего ТО» и «За сегодня»,
/// и обе считают один и тот же одометр — различает их только слово хозяина.
/// </param>
public sealed record MetricTile(
    string MetricId, TileKind Kind, TileSize Size, bool ShowLabel = true, TileChart? Chart = null,
    TileLimits? Limits = null, TileExtremum? Extremum = null, bool ShowHeatBar = true,
    int? Decimals = null, string Caption = "")
{
    /// <summary>
    /// Устойчивое имя <b>этой самой плитки</b> в раскладке. Позиция для этого не годится:
    /// перетаскивание меняет её, а точка отсчёта дистанции обязана остаться при своей плитке
    /// (решение владельца 10.08.2026 — «с последнего ТО» и «за сегодня» рядом, точки разные).
    /// <para>
    /// Пусто — плитка пришла из раскладки, собранной до этого правила: имя ей даёт экран при
    /// чтении и тут же сохраняет, иначе оно рождалось бы заново каждый запуск, а вместе с ним
    /// терялась бы и точка.
    /// </para>
    /// </summary>
    public string Id { get; init; } = "";

    /// <summary>Пустое место заданного размера.</summary>
    public static MetricTile Empty(TileSize size) => new("", TileKind.Empty, size) { Id = NewId() };

    /// <summary>
    /// Новое имя плитки. Восьми знаков хватает: имена живут в одной раскладке, а не во вселенной, —
    /// их там десятки.
    /// </summary>
    public static string NewId() => Guid.NewGuid().ToString("N")[..8];
}

/// <summary>
/// Свойства плитки-графика: за какое время он нарисован, лежит ли поверх него текущее число и
/// растянут ли он по своим крайним значениям.
/// </summary>
/// <param name="Zoom">
/// <c>true</c> — линия занимает высоту плитки целиком, от своего минимума до максимума: так виден
/// ход величины, у которой размах мал против самого значения (напряжение, температура).
/// <c>false</c> — низ шкалы прибит к нулю, и линия показывает долю от него.
/// </param>
/// <param name="Fill">Заливать ли под линией.</param>
/// <param name="Axis">Показывать ли шкалу значений слева. На четвертной плитке она съедает треть ширины.</param>
/// <param name="Smoothing">Какой стороной периода рисовать линию.</param>
public readonly record struct TileChart(
    TimeSpan Window,
    bool ShowValue,
    bool Zoom,
    bool Fill = true,
    bool Axis = true,
    ChartSmoothing Smoothing = ChartSmoothing.MinMax);

/// <summary>
/// Что показывать за период прореживания. История приходит корзинами по времени, и от каждой в ней
/// лежат <b>минимум и максимум</b> (план 23 §5.6) — по ним и выбирается, чем рисовать линию.
/// <para>
/// Кривой Безье вместо этого не делаем: она сглаживает короткие пики, а пик — то самое, ради чего на
/// график и смотрят. Сглаживание должно быть решением о данных, а не о рисунке.
/// </para>
/// </summary>
public enum ChartSmoothing
{
    /// <summary>Обе крайние точки корзины: линия дрожит, но не врёт ни одним пиком.</summary>
    MinMax,

    /// <summary>Только максимумы: видно, как высоко поднималось.</summary>
    Peaks,

    /// <summary>Только минимумы: видно, как низко проседало.</summary>
    Dips,
}

/// <summary>
/// Свойства плитки крайнего значения.
/// </summary>
/// <param name="Lowest">
/// <c>true</c> — помнить минимум, <c>false</c> — максимум. У напряжения и заряда интересен как раз
/// нижний край, у ШИМ и тока — верхний.
/// </param>
public readonly record struct TileExtremum(bool Lowest);

/// <summary>
/// Пороги плитки — жёлтый и красный. Одни на всё: по ним же красится подложка при текущем значении и
/// пики на её графике (решение владельца 05.08.2026 — порогов для графика и числа не разносим).
/// </summary>
/// <param name="Rising">
/// <c>true</c> — хуже, когда больше (ШИМ, ток, температура); <c>false</c> — когда меньше
/// (напряжение, заряд).
/// </param>
/// <param name="Warn">Жёлтая метка. <c>null</c> — её нет вовсе.</param>
/// <param name="Danger">Красная метка. <c>null</c> — её нет вовсе.</param>
/// <remarks>
/// <b>Метки независимы</b> (решение владельца 11.08.2026): ставится любая — только жёлтая, только
/// красная, обе или ни одной. Прежде одинокая метка молча отбрасывалась, и сохранить одну было
/// нельзя.
/// <para>
/// От этого зависит и шкала жара: при <b>двух</b> метках она натянута между ними — ноль у жёлтой,
/// единица у красной; при <b>одной</b> идёт от нуля до уставки (растущая величина) либо от уставки
/// до нуля (падающая), а цвет к концу шкалы приходит тот, чья метка стоит.
/// </para>
/// </remarks>
public readonly record struct TileLimits(double? Warn, double? Danger, bool Rising);
