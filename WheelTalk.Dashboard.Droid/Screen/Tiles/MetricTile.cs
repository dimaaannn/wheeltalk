namespace WheelTalk.Dashboard.Droid.Screen.Tiles;

/// <summary>
/// Ширина плитки в колонках сетки (план 23 §3.3). Сетка шестиколоночная — шесть есть НОК для одной,
/// двух и трёх плиток в ряд, — и значение здесь и есть спан: третьего представления ширины,
/// которое пришлось бы держать в согласии с этим, не заводим.
/// </summary>
public enum TileWidth
{
    /// <summary>Треть ряда — три плитки рядом.</summary>
    Third = 2,

    /// <summary>Половина ряда.</summary>
    Half = 3,

    /// <summary>Весь ряд.</summary>
    Full = 6,
}

public static class TileWidths
{
    /// <summary>
    /// Высота плитки в строках сетки (решение владельца 04.08.2026): узкая — <b>одна строка</b>,
    /// всё, что шире, — <b>две</b>. Две строки — потолок, выше плиток не бывает.
    /// <para>
    /// Высота выводится из ширины, а не задаётся отдельно: <see cref="TileWidth"/> — единственная
    /// ручка размера, и второй, которую пришлось бы держать с ней в согласии, здесь нет.
    /// </para>
    /// </summary>
    public static int Rows(this TileWidth width) => width == TileWidth.Third ? 1 : 2;
}

/// <summary>
/// Как рисуется плитка. Величина — параметр рисовальщика, а не его вид: ровно то, ради чего заведён
/// <c>MetricCatalogue</c> (план 23 §7 — «тип плитки на каждую величину» запрещён).
/// </summary>
public enum TileKind
{
    /// <summary>Текущее число из живого снимка.</summary>
    Value,

    // Chart (график из таблицы телеметрии) и Extremum (максимум/минимум с независимым сбросом)
    // приходят шагами 6 и 7 плана 23. Их здесь нет намеренно: рисовальщик без своих данных — это
    // пустая плитка, а не задел.
}

/// <summary>
/// Одна плитка раскладки: чем рисовать, что рисовать и какой ширины. На этом шаге раскладка зашита
/// в коде (<see cref="TilesLayout"/>); правка и хранение её в настройке — шаг 5 плана 23.
/// </summary>
/// <param name="MetricId">Имя величины из <c>MetricCatalogue</c>.</param>
public sealed record MetricTile(string MetricId, TileKind Kind, TileWidth Width);
