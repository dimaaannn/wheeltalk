namespace WheelTalk.Dashboard.Droid.Screen.Tiles;

/// <summary>
/// Где живут точки отсчёта плиток-дистанций. Тот же порядок, что у раскладки
/// (<see cref="ITileLayoutStore"/>): экран получает хранилище снаружи и разницы между настройкой
/// приложения и файлом стенда не знает.
/// <para>
/// <b>Строкой, а не разобранным набором.</b> Точки — данные экрана, а не настройка человека: их не
/// показывают, не переводят и не правят руками, — хозяину хранилища знать про них нечего, кроме
/// того, что это строка, которая обязана пережить перезапуск. Кодек живёт в ядре
/// (<c>TripBaselines</c>) — там же, где и смысл этих чисел.
/// </para>
/// </summary>
public interface ITripBaselineStore
{
    /// <summary><c>null</c> — сохранённого нет: точки заведутся на первом же показании одометра.</summary>
    string? Load();

    /// <summary>
    /// Запомнить точки. Зовётся на заведении первой точки и на каждом сбросе — то есть считанные
    /// разы за поездку, а не на кадре.
    /// </summary>
    void Save(string json);
}
