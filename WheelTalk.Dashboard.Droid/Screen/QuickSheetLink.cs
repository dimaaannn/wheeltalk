namespace WheelTalk.Dashboard.Droid.Screen;

/// <summary>
/// Переход на другой экран приложения — «Данные», «Поездки», «Настройки» (план 25 §2, шаг 2).
/// <para>
/// <b>Не команда и не корешок.</b> Команда делает что-то с колесом или телефоном <i>сейчас</i>, и
/// человек после неё продолжает ехать; корешок (<see cref="QuickSheetScreen"/>) меняет содержимое
/// той же рамки и один из них всегда выбран. Переход уводит с главного экрана совсем — выбранным
/// он не бывает и состояния не имеет. Три породы в одном списке и дали ряд из десяти, по которому
/// приходилось искать глазами.
/// </para>
/// <para>
/// Живёт последним разделом шторки, «Перейти», узкой кнопкой с обводкой и без заливки: рука не
/// должна путать «показать другое здесь» с «уйти отсюда».
/// </para>
/// </summary>
public sealed class QuickSheetLink
{
    /// <summary>Значок перехода — номер vector drawable (<see cref="QuickIcons"/>). В шторке он обязан быть уникальным: на два разных дела один знак и был половиной жалобы (план 25 §1).</summary>
    public required int Icon { get; init; }

    /// <summary>Слово перехода — имя экрана, куда он ведёт. Забота вызывающего: библиотека слов не держит.</summary>
    public required string Label { get; init; }

    /// <summary>Открыть экран. Синхронно: у перехода нет судьбы, которую стоило бы показывать подсветкой, — экран либо открылся, либо человек остался на месте.</summary>
    public required Action Open { get; init; }
}
