namespace WheelTalk.Droid.Configuration;

/// <summary>
/// К какому колесу подключаться самому. Заводского адреса нет и быть не должно: **пусто** — это
/// первый запуск у человека, который колесо ещё не выбрал, и приложение говорит ему об этом плашкой
/// «Колесо не выбрано» с переходом в поиск по нажатию.
/// <para>
/// До 01.08.2026 здесь стоял адрес Sherman L владельца — приложение жило на одном телефоне, и это
/// было удобно. Раздавать такую сборку нельзя: чужой телефон при первом запуске ломился бы к чужому
/// колесу, а поймав его в зоне действия — подключился бы к нему по-настоящему.
/// </para>
/// <para>
/// Заполняется, когда колесо выбрано на экране поиска: <c>UserSettingsStore.SaveWheel</c> пишет
/// адрес в пользовательский файл настроек, и дальше приложение подключается само.
/// </para>
/// <para>
/// Протокола здесь больше нет. Он не выбирается человеком и не хранится: колесо опознаётся на
/// каждом подключении — по дереву GATT и по заголовку первого кадра (<c>WheelDetector</c>). Поле
/// <c>Protocol</c> осталось от прежнего порядка и не читалось ни одной строкой кода.
/// </para>
/// </summary>
public sealed class WheelOptions
{
    public const string SectionName = "Wheel";

    public string Address { get; set; } = "";
}
