namespace WheelTalk.Droid.Configuration;

/// <summary>
/// Как приложение обращается с экраном телефона. Отдельно от <c>DashboardOptions</c> нарочно: та
/// про то, что нарисовано на панели, и живёт в библиотеке, которая про телефон ничего не знает, —
/// а это про сам аппарат.
/// </summary>
public sealed class ScreenOptions
{
    public const string SectionName = "Screen";

    /// <summary>
    /// Не гасить экран, пока приложение открыто. **Живёт до перезапуска** и включается руками —
    /// кнопкой в шторке или строкой в настройках: забытый включённым, он сажает телефон за вечер,
    /// а решение «пусть горит» человек принимает под конкретную поездку, а не навсегда.
    /// <para>
    /// Действует ровно пока окно на переднем плане — этим флаг окна и хорош: ушли в фон, и экран
    /// снова живёт по правилам системы. Ручное выключение он не блокирует: кнопка питания гасит
    /// экран как обычно, флаг отменяет только таймаут бездействия.
    /// </para>
    /// </summary>
    public bool KeepOn { get; set; }

    /// <summary>
    /// Показывать панель поверх экрана блокировки: включил экран кнопкой — видишь приборы, не
    /// разблокируя ([план 16](../../docs/android-plan-16-screen-on-return.md) §2, способ А).
    /// **Выключено по умолчанию и включается руками**, как и <see cref="KeepOn"/>, и живёт так же —
    /// до перезапуска.
    /// <para>
    /// Даётся руками, а не берётся молча, потому что цена не в батарее, а в том, что панель
    /// заменяет собой замок: поднявший телефон видит поездку и достаёт шторку, из которой команды
    /// колесу — включая «Отключить» — нажимаются без разблокировки. Это решение владельца телефона
    /// под конкретную поездку.
    /// </para>
    /// <para>
    /// Экран приложение при этом **не будит**: `SetTurnScreenOn` не ставится нарочно — телефон в
    /// кармане должен спать, а не светить панелью в темноте.
    /// </para>
    /// </summary>
    public bool ShowOverLock { get; set; }
}
