namespace WheelTalk.Droid.Configuration;

/// <summary>
/// Как приложение договаривается с Android об экономии заряда. Отдельно от <see cref="ScreenOptions"/>:
/// та про экран телефона, а это про право приложения жить, пока экран погашен.
/// </summary>
public sealed class PowerOptions
{
    public const string SectionName = "Power";

    /// <summary>
    /// Просить исключить приложение из экономии заряда. Спрашивается при запуске и ровно до тех пор,
    /// пока исключение не выдано: выданное система помнит сама, и повторов не будет.
    /// <para>
    /// Зачем вообще: соединение с колесом держит служба переднего плана, но экран приложения она не
    /// держит — Android волен разобрать его, пока телефон заблокирован, а на устройствах с
    /// вендорской «оптимизацией» это происходит за минуты. Исключение — единственное, чем на это
    /// можно повлиять из приложения (план 11 §2.4, план 16).
    /// </para>
    /// <para>
    /// Выключатель есть, потому что просьба навязчива: она приходит на каждом запуске, пока
    /// исключения нет. Так же устроено у оригинала (<c>DialogHelper.checkBatteryOptimizationsAndShowAlert</c>,
    /// настройка <c>detectBatteryOptimization</c>, по умолчанию включена).
    /// </para>
    /// </summary>
    public bool WarnAboutBatterySaver { get; set; } = true;
}
