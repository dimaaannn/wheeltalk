namespace WheelTalk.Droid.Configuration;

/// <summary>
/// Пишется ли поток телеметрии. **Решение владельца 05.08.2026** — два положения вместо трёх, и
/// запись потока <b>больше не привязана к поездке</b>: либо пишем и удаляем через сутки, либо не
/// пишем вовсе.
/// <para>
/// Прежнее решение (03.08.2026, план 23 §5.7) держало три положения, среднее — «только в поездке» —
/// было умолчанием. Отменено потому, что графики берут данные из потока: вне поездки поток не шёл,
/// и человек видел пустой график, не понимая причины. Экран, который показывает историю, должен
/// показывать её всегда.
/// </para>
/// <para>
/// Дыра, которой боялось прежнее решение, никуда не делась и здесь: при <see cref="Never"/> поездка
/// выйдет строкой с двумя датами и пустыми итогами, а аварийное закрытие «последним кадром» не
/// сработает — кадров нет. Оттого это и не тумблер «на всякий случай», а осознанный отказ, и
/// подсказка говорит о нём прямо.
/// </para>
/// </summary>
public enum TelemetryRecording
{
    /// <summary>
    /// Не пишется вовсе. Тогда нет ни графиков, ни разметки поездок — размечать нечего.
    /// </summary>
    Never,

    /// <summary>
    /// Пишется постоянно, поездка его лишь размечает. Значение по умолчанию с 05.08.2026: графики
    /// нужны и на стоянке, и при зарядке. Этого же режима просит план 9 §3 — кривая «напряжение
    /// покоя ↔ заряд» строится как раз тогда, когда колесо стоит.
    /// </summary>
    Always,
}
