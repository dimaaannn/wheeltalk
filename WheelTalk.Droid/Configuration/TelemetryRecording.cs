namespace WheelTalk.Droid.Configuration;

/// <summary>
/// Когда пишется поток телеметрии. Решение владельца 03.08.2026 (план 23 §5.7): поток к поездке
/// больше не привязан жёстко и может не существовать вовсе — человек вправе отказаться от записи.
/// <para>
/// Почему три положения, а не два: «выключено» из двух оставляет дыру — поездку всё ещё можно
/// начать, но она выйдет строкой с двумя датами и пустыми итогами, а аварийное закрытие «последним
/// кадром» не сработает вовсе, потому что кадров нет.
/// </para>
/// </summary>
public enum TelemetryRecording
{
    /// <summary>Не пишется вовсе; разметка поездок при этом недоступна — размечать нечего.</summary>
    Never,

    /// <summary>
    /// Вне разметки не пишется ничего, внутри — пишется. Значение по умолчанию: это в точности
    /// поведение приложения до плана 23, и миграция не меняет привычек человека.
    /// </summary>
    RideOnly,

    /// <summary>
    /// Пишется постоянно, поездка его лишь размечает. Тот самый режим, которого просит план 9 §3:
    /// зарядка и покой попадают в базу без поездки.
    /// </summary>
    Always,
}
