namespace WheelTalk.Tests.TestSupport;

/// <summary>
/// Одна коллекция на всех, кто заводит <see cref="TempDatabase"/>, — и она не про общий ресурс, а
/// про <b>очерёдность</b>: xunit гоняет классы параллельно, а <see cref="TempDatabase.Dispose"/>
/// зовёт <c>SqliteConnection.ClearAllPools()</c> — метод <b>процессный</b>, он чистит пулы всех
/// соединений разом. Значит завершающийся тест хранилища бьёт по соединениям соседа, который в этот
/// момент ещё работает. Классы в одной коллекции идут по очереди, и бить становится некого.
/// <para>
/// <b>Новый класс, который заводит <see cref="TempDatabase"/>, обязан вступить сюда</b> —
/// <c>[Collection(TempDatabaseCollection.Name)]</c>. Забыть значит вернуть ту самую связь: она не
/// падает сразу, а плавает — 08.08.2026 два теста хранилища упали по разу и оба прошли при повторе
/// (разбор в <c>docs/state.md</c>, «Плавают тесты хранилища»).
/// </para>
/// <para>
/// Остальной прогон параллелен, как и был: глушить параллельность всего прогона ради восьми классов
/// значило бы платить за связь там, где её нет.
/// </para>
/// </summary>
[CollectionDefinition(Name)]
public sealed class TempDatabaseCollection
{
    public const string Name = "База во временном каталоге";
}
