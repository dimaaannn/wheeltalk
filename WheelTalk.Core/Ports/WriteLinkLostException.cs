namespace WheelTalk.Core.Ports;

/// <summary>
/// Линк исчез, пока команда была в очереди или ждала подтверждения. Не поломка: колесо выключили,
/// оно уехало из радиуса, райдер нажал «отключиться» — доставлять уже некуда и некому.
/// <para>
/// Свой тип, а не <see cref="TimeoutException"/>, которым <see cref="SequentialWriteQueue"/>
/// отвечает на принятую, но не подтверждённую запись, — ответы разные. Тайм-аут значит «мы ждали
/// столько, сколько согласились ждать, и не дождались»: это предохранитель, и в журнале он
/// заслуженно ошибка. Этот — «ждать больше нечего», и в журнале ему место рядом с самим обрывом.
/// </para>
/// <para>
/// До появления этого типа разницы не было: обрыв связи стоил каждой команде в очереди полного
/// <c>confirmationTimeout</c>, а потом писался в журнал как ошибка записи. На InMotion P6
/// 02.08.2026 это дало красную строку с трассировкой на ровном месте — обрыв был уже пять секунд
/// как в журнале двумя строками выше.
/// </para>
/// </summary>
public sealed class WriteLinkLostException()
    : Exception("Связь оборвалась — команда не доставлена и доставлена не будет");
