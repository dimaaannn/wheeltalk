namespace WheelTalk.Core.Ports;

/// <summary>
/// Команда длиннее, чем влезает в одну запись на этом линке. Не «занято» и не обрыв: пока линк
/// живёт, повторять бессмысленно — размер записи задаётся согласованным при подключении MTU и до
/// переподключения не меняется. Потому бросается, а не отвечает «попробуй ещё» (договор
/// <see cref="SequentialWriteQueue"/>: бросок валит команду, отказ — повторяет).
/// <para>
/// Тип заведён ради того, чтобы отказ было видно. Стек Android на запись длиннее MTU не жалуется
/// — он отправляет первые MTU-3 байта и докладывает об успехе. Так команды InMotion V1 (22 байта)
/// уходили обрезанными до 20: колесо получало кадр без контрольной и хвоста <c>55 55</c>, молчало
/// в ответ, а в журнале стояло «Cmd.Sent» (дамп vivo I2407 от 07.08.2026). Молчаливое обрезание —
/// ровно тот род поломки, которую в журнале не найти, и стоил он одного выезда.
/// </para>
/// </summary>
public sealed class WriteTooLongException(int length, int limit)
    : Exception($"Команда {length} Б не влезает в запись {limit} Б — MTU этого линка меньше, чем нужно протоколу")
{
    /// <summary>Длина команды, которую не удалось отправить.</summary>
    public int Length { get; } = length;

    /// <summary>Сколько байт помещается в одну запись на этом линке (MTU минус ATT-заголовок).</summary>
    public int Limit { get; } = limit;
}
