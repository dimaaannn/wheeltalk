namespace WheelTalk.Core.Services;

/// <summary>
/// Когда погоня за колесом перестаёт быть обычным делом и стоит спросить о причине (план 11 §3.2).
/// <para>
/// Три ситуации на экране выглядят одинаково — «нет связи, N секунд»: колесо выключено или уехало
/// (погоня уместна), Bluetooth выключен и разрешение отозвано (погоня бессмысленна и будет вечной).
/// Спрашивать причину перед каждой попыткой — лишняя работа две сотни раз в час; спрашивать
/// никогда — вечная погоня с враньём на экране. Отсюда порог: несколько отказов подряд, и один
/// вопрос.
/// </para>
/// </summary>
public static class ChaseTrouble
{
    /// <summary>
    /// Сколько отказов подряд считать поводом спросить. Три — это первые секунды погони (паузы
    /// растут с полусекунды), то есть причина находится сразу, а не через минуту вранья; и это
    /// заведомо больше одного случайного отказа при живом колесе.
    /// </summary>
    public const int Threshold = 3;

    /// <summary>
    /// Спрашивать ли причину <b>сейчас</b>. Равенство, а не «больше либо равно»: вопрос задаётся
    /// один раз за погоню — дальше причина либо найдена и названа, либо её нет, и повторять
    /// проверку двести раз подряд значит вернуть ту самую лишнюю работу.
    /// </summary>
    public static bool ShouldAskWhy(int failuresInARow) => failuresInARow == Threshold;
}
