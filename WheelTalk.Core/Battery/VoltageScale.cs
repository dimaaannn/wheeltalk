namespace WheelTalk.Core.Battery;

/// <summary>
/// Чем меряет шкала напряжения: вольтами пакета или вольтами на банку (план 27 §27.4). Выбирает
/// человек; сама шкала на банку не переключается никогда.
/// </summary>
public enum VoltageScaleMode
{
    /// <summary>Вольты пакета — то, что лента показывала всегда. Заводское.</summary>
    Pack,

    /// <summary>
    /// Вольт на банку: живое напряжение пакета, делённое на <b>число из настройки колеса</b>.
    /// Не задано — лента возвращается к вольтам пакета.
    /// </summary>
    Cells,
}

/// <summary>
/// Во сколько раз вольты пакета больше того, что показывает лента. Чистая функция без состояния —
/// как и остальная семья плана 27, — и живёт она в ядре, а не в разметке, потому что стережёт
/// правило, а не рисование.
/// <para>
/// <b>Показ не гадает.</b> Каскад сюда не заглядывает вовсе: ряд у колеса не меняется, и решать
/// каждый кадр то, что решается один раз за всё время жизни колеса в приложении, незачем. Догадка
/// живёт за кнопкой «рассчитать» — она записывает ответ в настройку, а лента делит на записанное.
/// </para>
/// <para>
/// Делится <b>живое</b> напряжение пакета. Показывать измеренную банку умного BMS было бы честнее
/// на вид, но замер (§27.4, «Замер темпа BMS») это закрыл: полный оборот банок — 1,4–2,1 с против
/// 200 мс основного кадра, а лента существует ради просадки, которая в эти полторы секунды и
/// происходит.
/// </para>
/// </summary>
public static class VoltageScale
{
    /// <param name="packVolts">Напряжение пакета из основного кадра колеса. Ноль — кадра ещё не было.</param>
    /// <param name="cells">
    /// Ответ каскада. На шкалу пускается только слово человека: остальные ступени хороши для
    /// процентов заряда, но лента делит на записанное в настройке, а не на догадку.
    /// </param>
    /// <returns>Делитель, не меньший единицы. Единица означает «шкала в вольтах пакета».</returns>
    public static double Divisor(VoltageScaleMode mode, double packVolts, CellCount cells)
    {
        if (packVolts <= 0) return 1;

        double divisor = mode == VoltageScaleMode.Cells
            && cells is { Source: CellCountSource.UserSetting, Cells: > 0 }
                ? cells.Cells
                : 1;

        // Единичный ряд — не шкала, а испорченные данные: банка, равная целому пакету, бывает
        // только у пакета из одной банки, каких у нас нет. Такое честнее показать пакетом.
        return divisor > 1 ? divisor : 1;
    }
}
