namespace WheelTalk.Core.Battery;

/// <summary>
/// Чем меряет шкала напряжения: пакетом или ячейкой — и, если ячейкой, каким способом получен
/// делитель (план 27 §27.4). Пункт выбирает человек; сама шкала на ячейку не переключается никогда.
/// </summary>
public enum VoltageScaleMode
{
    /// <summary>Вольты пакета — то, что лента показывала всегда. Заводское.</summary>
    Pack,

    /// <summary>Вольт на ячейку по данным умного BMS.</summary>
    Bms,

    /// <summary>Вольт на ячейку делением на ряд, <b>заданный человеком</b>.</summary>
    Cells,
}

/// <summary>
/// Во сколько раз вольты пакета больше того, что показывает лента. Чистая функция без состояния —
/// как и остальная семья плана 27, — и живёт она в ядре, а не в разметке, потому что стережёт
/// правило, а не рисование.
/// <para>
/// <b>Режимы не смешиваются.</b> Расчётный режим не смотрит на банки BMS, даже когда они есть:
/// подмешай измеренное — и два пункта из трёх покажут одно и то же, а человеку станет не из чего
/// выбирать. Ввод человека — его собственное утверждение о колесе, и проверяется оно тем, что он
/// видит на шкале. Обратное тоже верно: среднее по банкам считается своим счётом
/// (<see cref="BmsCells"/>) и числа человека не спрашивает.
/// </para>
/// <para>
/// Режим, которому нечем считать (BMS молчит, ряд не задан), возвращается к вольтам пакета. Это не
/// ошибка, а обычный день у колеса без BMS.
/// </para>
/// </summary>
public static class VoltageScale
{
    /// <param name="packVolts">Напряжение пакета из основного кадра колеса. Ноль — кадра ещё не было.</param>
    /// <param name="bmsCellVolts">
    /// Средняя банка по данным BMS: сколько банок он насчитал, на столько и поделено. Ноль — банок
    /// никто не мерил.
    /// </param>
    /// <param name="cells">Ответ каскада: на шкалу пускается только слово человека.</param>
    /// <returns>Делитель, не меньший единицы. Единица означает «шкала в вольтах пакета».</returns>
    public static double Divisor(VoltageScaleMode mode, double packVolts, double bmsCellVolts, CellCount cells)
    {
        if (packVolts <= 0) return 1;

        double divisor = mode switch
        {
            VoltageScaleMode.Bms when bmsCellVolts > 0 => packVolts / bmsCellVolts,
            VoltageScaleMode.Cells when cells is { Source: CellCountSource.UserSetting, Cells: > 0 } => cells.Cells,
            _ => 1,
        };

        // Меньше единицы делитель быть не может: это означало бы ячейку выше целого пакета, то есть
        // не шкалу, а испорченные данные. Такое лучше показать пакетом, чем растянутой вдвое лентой.
        return divisor > 1 ? divisor : 1;
    }
}
