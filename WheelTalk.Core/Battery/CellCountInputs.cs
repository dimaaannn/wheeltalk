namespace WheelTalk.Core.Battery;

/// <summary>
/// Всё, чем кормится <see cref="CellCountResolver"/>. Готовые числа: класс сам никуда не ходит —
/// ни в настройки, ни в декодер, ни в состояние колеса (план 27, «Рамка»). Чего нет — <c>null</c>,
/// и это штатный случай, а не ошибка.
/// </summary>
public readonly record struct CellCountInputs
{
    /// <summary>
    /// Ряд, заданный человеком. Ноль и отрицательное считаются «не задано» — так настройка,
    /// хранимая целым числом, отдаёт своё «пусто».
    /// </summary>
    public int? ConfiguredCells { get; init; }

    /// <summary>
    /// Сколько ячеек насчитал умный BMS (у Gotway это <c>_smartBmsCells</c>). Ноль — «BMS не
    /// отвечал», ровно как у декодера.
    /// </summary>
    public int? SmartBmsCells { get; init; }

    /// <summary>
    /// Чем на этот вопрос отвечает сам протокол — то самое, чем декодеры отвечали до появления
    /// каскада. Ноль — «протокол молчит» (модель ещё не опознана).
    /// <para>
    /// Число берётся <b>как есть</b>, без сверки со списком правдоподобных рядов: спорить с
    /// протоколом не дело этой ступени. Известное расхождение Begode при настройке <c>"3"</c>
    /// (32 ячейки против 28 по напряжению) поэтому проезжает насквозь — чинится оно отдельным
    /// осознанным шагом, а не молчаливой подменой числа, по которому у людей уже накоплены поездки.
    /// </para>
    /// </summary>
    public int? ProtocolCells { get; init; }

    /// <summary>Текущее напряжение пакета, вольты.</summary>
    public double? PackVolts { get; init; }

    /// <summary>
    /// Процент заряда, названный <b>самим колесом</b>. Только сырой: наши «улучшенные проценты»
    /// сюда не годятся — они пересчитаны из напряжения и числа ячеек, то есть доказывали бы число
    /// самим собой.
    /// <para>
    /// Должен быть снят <b>в тот же момент</b>, что и <see cref="PackVolts"/>: ступень разбирает
    /// именно пару, и разновременные числа дадут ложный ответ вместо честного «не знаю».
    /// </para>
    /// </summary>
    public int? WheelPercent { get; init; }

    /// <summary>
    /// Наибольшее напряжение, какое у этого колеса вообще видели, вольты. Не задано — догадка
    /// возьмёт <see cref="PackVolts"/>, он максимуму нижняя граница.
    /// <para>
    /// Чем выше заряд был в момент замера, тем точнее догадка; напряжение <b>на зарядке</b>
    /// максимум портит и ряд завышает — отсекать его дело того, кто максимум копит.
    /// </para>
    /// </summary>
    public double? MaxPackVolts { get; init; }
}
