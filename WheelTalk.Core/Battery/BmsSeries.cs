using WheelTalk.Core.Contracts;

namespace WheelTalk.Core.Battery;

/// <summary>
/// Сколько банок насчитал умный BMS — там, где он не говорит этого прямо. Надстройка над портом:
/// декодер Ветерана раскладывает банки по массиву, а счёт их выводится здесь, снаружи (план 27
/// §27.4).
/// <para>
/// Ступень <see cref="CellCountSource.SmartBms"/> до сих пор питалась одним Gotway — у него число
/// приходит готовым. У Ветерана массив есть, а числа нет, и вывести его из одного отсева мусора
/// нельзя: хвостовые места заполняются произвольными байтами кадра, и 2,5 В там от настоящей банки
/// не отличить ничем. Отличает <b>сверка суммы с напряжением пакета</b>: при верном ряде сумма
/// сходится с ним до десятых (замер по фикстуре — медиана +0,12 В).
/// </para>
/// <para>
/// Состояния нет и не нужно: ответ разовый, по нажатию кнопки «рассчитать». Кадр под нагрузкой, где
/// пакет просел и сумма ни с чем не сходится, честно отвергается — ответит ступень ниже, а человек
/// нажмёт ещё раз.
/// </para>
/// </summary>
public static class BmsSeries
{
    /// <summary>
    /// Границы, за которыми число из массива — вообще не показание банки: незаполненное место
    /// (ноль) или байты кадра, прочитанные как банка (наблюдали 33,365 В). Широкие нарочно, и это
    /// <b>не</b> <see cref="LiIonCell"/>: там узость — суть дела, здесь вопрос другой, «банка ли это
    /// вообще». Глубоко разряженная банка остаётся банкой и в счёт входит.
    /// </summary>
    private const double MinCellVolts = 0.5;
    private const double MaxCellVolts = 5.0;

    /// <summary>
    /// Насколько сумма вправе разойтись с напряжением, чтобы счёт считался сошедшимся, — доля
    /// банки. Четверть: под нагрузкой пакет проседает на вольты, и такой кадр отвергается, а на
    /// стоянке, где кнопку и жмут, расхождение в разы меньше.
    /// </summary>
    private const double ToleranceOfCell = 0.25;

    /// <summary>
    /// Насколько ответ должен быть лучше следующего за ним, чтобы считаться однозначным, — доля
    /// банки. Соседний ряд отличается по сумме ровно на банку, поэтому у настоящего ответа отрыв
    /// огромен; мал он там, где сумма встала между двумя рядами, и вот тогда молчание честнее.
    /// </summary>
    private const double SeparationOfCell = 0.5;

    /// <summary>
    /// Ток, выше которого сверять нечего, ампер. Не осторожность, а необходимость, и стоила она
    /// одного упавшего теста: под нагрузкой пакет проседает на вольты — на записи Sherman L до
    /// 3,5 В при 24 А, — а это почти целая банка. Просевшая сумма честно сходится с рядом
    /// <b>на единицу меньше</b> настоящего, и оба порога ниже такой ответ пропускают: он не
    /// сомнительный, он уверенно неверный.
    /// <para>
    /// Двойка — то же число, каким приложение считает колесо разгруженным в других местах. На
    /// стоянке, где кнопку и жмут, расхождение суммы с напряжением — сотые доли вольта.
    /// </para>
    /// </summary>
    private const double RestingAmps = 2;

    /// <param name="packVolts">Напряжение пакета из основного кадра. Ноль — сверять не с чем.</param>
    /// <param name="amps">
    /// Ток в тот же момент. Под нагрузкой ступень молчит: сверять сумму с просевшим напряжением
    /// нельзя.
    /// </param>
    /// <returns>Ряд по данным BMS либо ноль — «BMS не ответил или ответ не сошёлся».</returns>
    public static int Count(SmartBms first, SmartBms second, double packVolts, double amps)
    {
        if (packVolts <= 0 || Math.Abs(amps) > RestingAmps) return 0;

        int count = CountIn(first, packVolts);
        return count > 0 ? count : CountIn(second, packVolts);
    }

    /// <summary>
    /// Считается по одному пакету: у Ветерана их два, и каждый держит всё напряжение — пакеты
    /// включены параллельно (сверено по сырому дампу поездки). Последовательное включение сумму с
    /// напряжением не сведёт, и ступень промолчит: лучше уступить протоколу, чем назвать половину
    /// ряда целым.
    /// <para>
    /// Ряд берётся <b>подряд от начала</b>: массив заполняется страницами, и пока пришли не все,
    /// подряд идущих банок меньше, чем в пакете, — сумма не сойдётся, и кадр отвергнется целиком.
    /// Это и есть правило «протух кусок — отбрасываем пакет»: дырявый пакет сюда просто не пройдёт.
    /// </para>
    /// </summary>
    private static int CountIn(SmartBms bms, double packVolts)
    {
        double sum = 0;
        double best = double.MaxValue;
        double runnerUp = double.MaxValue;
        int answer = 0;

        for (int i = 0; i < bms.Cells.Length; i++)
        {
            double cell = bms.Cells[i];
            if (cell is < MinCellVolts or > MaxCellVolts) break;

            sum += cell;
            double residual = Math.Abs(sum - packVolts);

            if (residual < best)
            {
                runnerUp = best;
                best = residual;
                answer = i + 1;
                continue;
            }

            if (residual < runnerUp) runnerUp = residual;
        }

        if (answer == 0) return 0;

        // Мерка — сама банка этого пакета, а не абсолютные вольты: у 20S и у 56S она одна и та же
        // по смыслу, но разная по величине лишь настолько, насколько разные банки.
        double cellVolts = SumOf(bms, answer) / answer;
        bool converged = best <= cellVolts * ToleranceOfCell;
        bool unambiguous = runnerUp - best >= cellVolts * SeparationOfCell;

        return converged && unambiguous ? answer : 0;
    }

    private static double SumOf(SmartBms bms, int count)
    {
        double sum = 0;
        for (int i = 0; i < count; i++) sum += bms.Cells[i];
        return sum;
    }
}
