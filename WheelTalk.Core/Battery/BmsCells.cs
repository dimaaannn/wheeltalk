using WheelTalk.Core.Contracts;

namespace WheelTalk.Core.Battery;

/// <summary>
/// Средняя банка по данным умного BMS — надстройка над портом, а не правка его (план 27 §27.4).
/// <para>
/// BMS шлёт только сами банки, тремя блоками; среднее, минимум, максимум и сумму досчитывает
/// портированный код, и трогать его поля правилами нельзя — порт должен оставаться сверяемым.
/// Поэтому шкала считает своё среднее здесь.
/// </para>
/// </summary>
public static class BmsCells
{
    /// <summary>
    /// Границы, за которыми число из массива — вообще не показание банки: незаполненное место
    /// (ноль) или байты кадра, прочитанные как банка (наблюдали 33,365 В).
    /// <para>
    /// Широкие нарочно, и это <b>не</b> <see cref="LiIonCell"/>. Там узость 2,8…4,25 — суть дела:
    /// ею <see cref="CellCountResolver"/> отбрасывает невозможные ряды. Здесь вопрос другой — не
    /// «здорова ли банка», а «банка ли это вообще»: глубоко разряженная банка остаётся банкой и в
    /// среднее входит, даже утягивая его вниз, потому что это настоящее состояние пакета.
    /// </para>
    /// </summary>
    private const double MinCellVolts = 0.5;
    private const double MaxCellVolts = 5.0;

    /// <summary>
    /// Среднее по банкам обоих пакетов (у Sherman L их два, и оба настоящие). Ноль — банок никто не
    /// мерил: BMS либо нет, либо кадра с банками ещё не было.
    /// <para>
    /// Порядок отбора двойной, и обе половины нужны. <b>Счёт</b> говорит, докуда смотреть: хвост
    /// последнего блока заезжает за конец пакета, а произвольный байт кадра может прочитаться как
    /// вполне правдоподобные 2,5 В — от настоящей банки такое не отличить ничем, кроме счёта.
    /// <b>Границы</b> отсеивают незаполненные места внутри этих пределов: блоки приходят в любом
    /// порядке, и пока пришёл только последний, две трети массива — нули. Без этого лента при
    /// каждом подключении Ветерана вспыхивала бы полностью красной.
    /// </para>
    /// <para>
    /// Делится на число выживших, а не на счёт: поделить на то, чего не считали, — тот же обман,
    /// только тише.
    /// </para>
    /// </summary>
    public static double Average(SmartBms first, SmartBms second)
    {
        double total = 0;
        int counted = 0;

        Add(first, ref total, ref counted);
        Add(second, ref total, ref counted);

        return counted > 0 ? total / counted : 0;
    }

    private static void Add(SmartBms bms, ref double total, ref int counted)
    {
        // Два поля, потому что декодеры называют счёт по-разному: Ветеран пишет CellCount, Gotway —
        // CellNum. Незаполненное — ноль в обоих, поэтому берётся то, что заполнено.
        int limit = Math.Min(Math.Max(bms.CellCount, bms.CellNum), bms.Cells.Length);

        for (int i = 0; i < limit; i++)
        {
            double cell = bms.Cells[i];
            if (cell is < MinCellVolts or > MaxCellVolts) continue;

            total += cell;
            counted++;
        }
    }
}
