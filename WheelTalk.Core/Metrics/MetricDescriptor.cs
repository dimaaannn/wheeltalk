using WheelTalk.Core.Contracts;

namespace WheelTalk.Core.Metrics;

/// <summary>
/// Одна величина телеметрии, описанная, а не нарисованная (план 23 §3.1) — тот же приём, которым
/// <c>SettingsCatalogue</c> описывает настройки. Плитка знает про величину ровно это: как её
/// назвать, как достать и есть ли по ней история.
/// <para>
/// Новая величина — строка в <see cref="MetricCatalogue"/>, а не новый класс: это и есть требование
/// «плитки универсальные». Тип плитки (<c>Value</c>, позже <c>Chart</c> и <c>Extremum</c>) — это
/// рисовальщик, а величина — его параметр.
/// </para>
/// </summary>
public sealed class MetricDescriptor
{
    /// <summary>
    /// Устойчивое имя величины: им раскладка ссылается на неё в настройке (план 23 §3.4), поэтому
    /// переименование — это потеря чужой раскладки. Совпадает с <see cref="Column"/> там, где
    /// колонка есть.
    /// </summary>
    public required string Id { get; init; }

    /// <summary>
    /// Ключ ресурса, а не текст: хранимое значение не должно зависеть от языка — то самое, на чём
    /// оригинал потерял сохранённую раскладку плиток (см. <c>SettingDescriptor.LabelKey</c>).
    /// </summary>
    public required string LabelKey { get; init; }

    /// <summary>Ключ ресурса единицы. <c>null</c> — величина безразмерная (код режима, статус).</summary>
    public string? UnitKey { get; init; }

    /// <summary>
    /// Знаков после запятой при показе — <b>умолчание типа величины</b>, а не потолок: плитка вправе
    /// назначить своё число (<see cref="MetricRounding"/>). Показа это касается целиком: в базу и в
    /// историю идёт сырое значение.
    /// </summary>
    public int Decimals { get; init; }

    /// <summary>
    /// Как достать величину из живого снимка. <c>null</c> значит <b>«колесо молчит»</b>, и плитка
    /// рисует прочерк, а не ноль: у величины, которой это семейство протоколов не сообщает, нет
    /// значения вовсе — правило общее с записью в базу, см. <see cref="WheelReports"/>.
    /// </summary>
    public required Func<TelemetrySnapshot, double?> Read { get; init; }

    /// <summary>
    /// Имя колонки в таблице телеметрии. <c>null</c> значит «живьём есть, графика нет»: величина
    /// показывается плиткой <c>Value</c>, но истории по ней в базе не лежит, и график по ней экран
    /// предлагать не вправе (план 23 §3.2 — отказ на входе, а не пустая плитка).
    /// </summary>
    public string? Column { get; init; }

    /// <summary>
    /// На что умножить хранимое значение колонки, чтобы получить то же число, что отдаёт
    /// <see cref="Read"/>. База держит целые (сотые доли единицы — план 8 §2.1, метры у пробега,
    /// проценты и коды как есть), а плитка и график обязаны показывать одно и то же: без общего
    /// правила пересчёта у величины завелось бы два ответа на вопрос «сколько», и разошлись бы они
    /// молча.
    /// <para>
    /// Сотые — умолчание, потому что так хранится большинство. Исключения названы в
    /// <see cref="MetricCatalogue"/> строкой рядом с колонкой.
    /// </para>
    /// </summary>
    public double ColumnScale { get; init; } = 0.01;
}
