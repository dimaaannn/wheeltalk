namespace WheelTalk.Core.Metrics;

/// <summary>
/// Точка истории величины. Время — unix ms, теми же числами, что лежат в колонке <c>at</c> таблицы
/// телеметрии: перевод в <see cref="DateTimeOffset"/> нужен подписи оси, а не самой точке, и делать
/// его на каждую из тысячи — работа впустую.
/// </summary>
public readonly record struct MetricPoint(long AtMs, double Value);

/// <summary>
/// История одной величины за одно окно — всё, что плитка-график берёт от хранилища (план 23 §3.2,
/// §5.6). Контракт узкий намеренно: плитка спрашивает про свою величину и своё окно, а <b>чем</b>
/// это читается — её не касается.
/// <para>
/// Асинхронность здесь не украшение: за реализацией SQLite, а запрос к нему с потока отрисовки —
/// заикание (§5.6). Зовётся по таймеру раз в секунду-две, а не на кадр телеметрии.
/// </para>
/// <para>
/// Значения приходят в тех же единицах, в которых их показывает плитка
/// (<see cref="MetricDescriptor.ColumnScale"/>): километры в час, вольты, проценты. Хранимое
/// представление — забота хранилища, и наружу оно не выходит.
/// </para>
/// </summary>
public interface IMetricHistory
{
    /// <param name="metricId">Имя величины из <see cref="MetricCatalogue"/>.</param>
    /// <param name="from">Начало окна включительно.</param>
    /// <param name="to">Конец окна включительно.</param>
    /// <param name="points">
    /// Сколько точек нужно рисующему — обычно ширина плитки в пикселях. Это не «сколько строк
    /// вернуть»: строки прореживаются корзинами по времени, и от каждой корзины остаются минимум и
    /// максимум (§5.6). Брать каждую N-ю нельзя — так теряется пик ШИМ, ради которого график и
    /// смотрят.
    /// </param>
    /// <returns>
    /// Точки по возрастанию времени. Пусто — истории нет: величина без колонки, окно вне срока
    /// хранения либо запись телеметрии выключена. Отличать эти случаи от «ровно ноль» обязан
    /// вызывающий: пустой график и график по нулю — разные картинки (§5.7).
    /// </returns>
    Task<IReadOnlyList<MetricPoint>> ReadAsync(
        string metricId, DateTimeOffset from, DateTimeOffset to, int points, CancellationToken cancel);
}
