namespace WheelTalk.Core.Tiles;

/// <summary>
/// Неподвижная запятая: показание встаёт в бокс <b>самой широкой строки, какую эта плитка уже
/// показывала</b>, и короткое значение не двигает уже стоящие цифры (решение владельца 11.08.2026).
/// <para>
/// <b>Откуда мельтешение.</b> Строка центруется по своей фактической ширине, а ширина меняется на
/// живом снимке: «9,8» сменилось на «10,2» — цифры поехали; ток ушёл в рекуперацию, появился
/// минус — поехали снова. Пять раз в секунду, на каждой плитке. Читать такую раскладку нельзя, и
/// дело не в разрядах: двигает всё, что меняет длину строки.
/// </para>
/// <para>
/// <b>Чем крепится.</b> Слева дописываются пробелы до ширины бокса. Начертание моноширинное
/// (<c>PaintRuler.Mono</c>), пробел в нём ровно шириной цифры, а хвост держит формат — знаков после
/// запятой у плитки фиксированное число. Значит равная длина строки означает <b>равное место
/// запятой</b>, и одним этим правилом закрываются и разряды, и минус, и любая будущая перемена
/// длины. Дописывать справа нельзя: хвостовые пробелы при центровании отбрасываются разметкой, и
/// подпорка вышла бы мнимой.
/// </para>
/// <para>
/// <b>Бокс растёт и никогда не убывает</b> — как и счёт увиденных разрядов, которым садится кегль
/// (<c>MetricNumber.Widest</c>): оба считаются от одного и того же увиденного, поэтому подпорка
/// заведомо влезает в тот кегль, что уже подобран. Живёт она до пересоздания экрана: хранить её
/// незачем, а держать запас под знак, который, может, никогда не придёт, — значит платить местом за
/// догадку.
/// </para>
/// </summary>
public static class NumberBox
{
    /// <summary>
    /// Показание, поставленное в бокс шириной <paramref name="width"/> знаков. Строка шире бокса
    /// остаётся как есть: обрезать показание, чтобы оно встало ровно, — обмен правды на красоту.
    /// </summary>
    /// <param name="text">Готовый текст показания — уже с нужным числом знаков после запятой.</param>
    /// <param name="width">Ширина бокса в знаках: столько же, сколько в худшей строке этой плитки.</param>
    public static string Fit(string text, int width)
    {
        // Прочерк — не число: равнять в нём нечего, а прижатый к правому краю он читался бы как
        // обрубок числа. Молчащая величина стоит по середине плитки, как стояла.
        if (!HasDigits(text)) return text;

        return text.Length >= width ? text : text.PadLeft(width);
    }

    private static bool HasDigits(string text)
    {
        foreach (char sign in text)
        {
            if (char.IsDigit(sign)) return true;
        }

        return false;
    }
}
