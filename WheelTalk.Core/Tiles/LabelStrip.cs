namespace WheelTalk.Core.Tiles;

/// <summary>
/// Полоска подписи плитки — <b>одно число на разметку и на бюджет подбора кегля</b>, и считается оно
/// здесь. Разметка отступает им содержимое (<c>TileView.LabelStripPx</c>), бюджет вычитает его же
/// (<see cref="TileMetrics.SquareLabelPx"/> и <c>LabelHeightPx</c>); разойдись эти два счёта —
/// подпись либо ляжет на число, либо отнимет у него место впустую.
/// <para>
/// <b>Почему в ядре.</b> Меряет краску тот, у кого есть шрифт, — <c>TileLabelStyle</c> на Android;
/// но сама формула к платформе отношения не имеет, а замок, повторяющий её у себя, стережёт свою
/// копию, а не боевой счёт. Здесь её зовут обе стороны, и тесты в том числе.
/// </para>
/// </summary>
public static class LabelStrip
{
    /// <summary>
    /// Место, которое подпись забирает у содержимого сверху: от верха содержимого (край плитки без
    /// общего поля) до низа краски.
    /// <para>
    /// Общее поле вычитается потому, что подпись сидит <b>выше</b> него — на своём малом угловом
    /// отступе, снаружи полей, — а содержимое живёт внутри них.
    /// </para>
    /// </summary>
    /// <param name="insetPx">Угловой отступ: где стоит видимая кромка подписи от края плитки.</param>
    /// <param name="inkTopPx">Верх краски строки от базовой линии — отрицательный.</param>
    /// <param name="inkBottomPx">Низ краски строки: у капса с выносом он ниже базовой линии.</param>
    /// <param name="paddingPx">Общее поле плитки.</param>
    public static float Px(float insetPx, float inkTopPx, float inkBottomPx, float paddingPx) =>
        insetPx + (inkBottomPx - inkTopPx) - paddingPx;
}
