namespace WheelTalk.Core.Tiles;

/// <summary>
/// Где начинается каждая строка сетки, когда строки <b>разной высоты</b>. До разделителя все они
/// были одной меры, и место строки считалось умножением; разделитель (решение владельца 11.08.2026)
/// — самостоятельный элемент во всю ширину и ростом заметно ниже плитки, и умножение перестало
/// отвечать на вопрос «сколько сверху».
/// <para>
/// <b>Считается сложением заранее, а не по требованию.</b> Укладчик проходит список дважды: сперва
/// раскладывает элементы по клеткам и узнаёт, какие строки заняты разделителем, потом складывает
/// высоты — иначе высота строки зависела бы от того, докуда дошёл проход, и низ раскладки поехал бы
/// при каждой перестановке.
/// </para>
/// </summary>
public static class TileRows
{
    /// <summary>
    /// Верх каждой строки: сумма высот всех, что выше. Ответ длиннее входа на единицу — последним
    /// числом идёт низ всей сетки, он же её полная высота.
    /// </summary>
    public static float[] Tops(IReadOnlyList<float> heights)
    {
        var tops = new float[heights.Count + 1];

        for (int row = 0; row < heights.Count; row++) tops[row + 1] = tops[row] + heights[row];

        return tops;
    }
}
