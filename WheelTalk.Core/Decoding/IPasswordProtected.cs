namespace WheelTalk.Core.Decoding;

/// <summary>
/// Протокол, который до пароля не разговаривает вовсе. Сейчас такой один — InMotion V1: колесо
/// молчит, пока не получит шесть цифр, и отличить «пароль не тот» от «колесо не отвечает» снаружи
/// нечем — молчание в обоих случаях одинаковое.
/// <para>
/// Отдельным интерфейсом, а не полем <see cref="IWheelDecoder"/>: четырём остальным декодерам
/// пароль не нужен, и пустое событие в каждом из них врало бы о протоколе. Проверка через
/// <c>is IPasswordProtected</c> — тот же приём, которым <c>WheelService</c> уже находит
/// <see cref="IDisposable"/> у декодера с таймером.
/// </para>
/// <para>
/// <b>Отклонение от оригинала</b> (AGENTS.md, «Отклонения от оригинала»). WheelLog пароля не
/// спрашивает вовсе: ни окна, ни строки в настройках — во всём его коде <c>passwordForWheel</c>
/// пишется только из <c>ScanActivity</c> (строки 82 и 191) и только пустой строкой. Заводится он
/// при этом исправно: сеттер <c>AppConfig.passwordForWheel</c> дополняет значение нулями слева до
/// шести цифр, то есть <c>""</c> сохраняется как <c>"000000"</c>, ветка INMOTION в
/// <c>WheelData.detectWheel</c> видит непустую длину и запускает опрос. <b>Первый пароль у нас и у
/// него один и тот же.</b> Разница дальше: колесу с заданным PIN оригинал молча сдаётся, а мы
/// говорим об этом человеку и указываем, где пароль задать. Второе, помельче: он стирает пароль
/// при каждом выборе колеса из списка, у нас пароль живёт слоем этого колеса и выбор переживает.
/// </para>
/// </summary>
public interface IPasswordProtected
{
    /// <summary>
    /// Стоим ли сейчас на пароле — то есть подтвердилось ли, что колесо нас не пускает.
    /// <para>
    /// Состоянием, а не событием: экран Android разбирают и собирают заново, и подписчик, слушавший
    /// в тот миг, до вернувшегося не доживёт. Состояние же спрашивают каждый кадр, и ответ верен
    /// всегда — включая экран, созданный уже после отказа.
    /// </para>
    /// </summary>
    bool AwaitingPassword { get; }

    /// <summary>
    /// Пароль в настройках сменился — начать разговор заново, не переподключаясь. Сам пароль сюда
    /// не передаётся: декодер читает его из <see cref="Ports.IWheelConfig"/> на каждом такте, а
    /// живой объект настроек уже обновлён слоем к моменту вызова.
    /// </summary>
    void RestartAuthentication();
}
