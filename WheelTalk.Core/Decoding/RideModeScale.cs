namespace WheelTalk.Core.Decoding;

/// <summary>
/// В каком виде колесо LeaperKim принимает «режим езды» — тремя именованными положениями или
/// плавной шкалой. Это <b>не</b> про жёсткость педалей: у производителя это две разные,
/// взаимоисключающие настройки на разных опкодах (<c>docs/wheel-settings-architecture.md</c> §7).
/// </summary>
public enum RideModeScale
{
    /// <summary>Три положения — мягко / средне / жёстко (<c>SETs</c>/<c>SETm</c>/<c>SETh</c>).</summary>
    ThreePosition,

    /// <summary>Плавная шкала. Она же умолчание для всего, чего мы не знаем, — см. таблицу.</summary>
    Continuous,
}

/// <summary>
/// Поколение колеса по версии протокола — <c>docs/wheel-settings-architecture.md</c> §7,
/// <c>docs/veteran-commands-import-plan.md</c> §5.
/// <para>
/// <b>Чем эта таблица распоряжается, а чем нет.</b> Только «режимом езды» (опкод 12, у нас — порт
/// <c>VeteranDecoder.BuildUpdatePedalsMode</c>). Жёсткости педалей (опкод 15) она не касается
/// вовсе: там шкала всегда плавная, а есть ли такая настройка у колеса, говорит сентинел
/// <c>128</c> в его же телеметрии (<c>ControlActivity.java:392-395</c>) — признак точнее любого
/// каталога моделей. Спутать эти две настройки легко, и цена ошибки — замок, поставленный не на ту
/// команду.
/// </para>
/// <para>
/// <b>Откуда границы.</b> Каталог производителя (<c>Util.CAR_DATA_JSON</c>, сборка 59) делит модели
/// ровно по версии железа с порогом <c>0050</c>: <c>continuousSoftHardSet: true</c> у LYNX
/// (<c>0050</c>), Sherman-L (<c>0060</c>), Patton-S (<c>0070</c>); <c>false</c> у Sherman
/// (<c>0010</c>), ShermanMax (<c>0011</c>), Abrams (<c>0020</c>), Sherman-s (<c>0030</c>), Patton
/// (<c>0040</c>). Тем же числам отвечают наши версии протокола 1..7 (<c>VeteranDecoder.cs:357-372</c>).
/// </para>
/// <para>
/// <b>Почему неизвестное — плавная шкала, а не молчание.</b> Решение владельца 16.08.2026: «на всех
/// новых моделях — плавная шкала», и «команда не того формата не должна причинить ущерба колесу, мы
/// можем пойти на такой риск». Так же поступает сам производитель: отсутствие карточки модели стоит
/// у него в одной ветке с плавной шкалой — <c>carInfoByHardVersion == null ||
/// isContinuousSoftHardSet()</c> (<c>SetRideModeActivity.java:69</c>). И та же арифметика:
/// неизвестные нам модели — это, как правило, новые (Oryx, Lynx S, Nosfet), а плавная шкала именно
/// у новых.
/// </para>
/// </summary>
public static class RideModeScales
{
    /// <summary>
    /// Версия протокола → вид «режима езды». Старое поколение перечислено поимённо, всё прочее —
    /// умолчание: список известных нам колёс кончается там, где кончается разобранный каталог, а
    /// колёса не кончаются.
    /// </summary>
    public static RideModeScale FromProtocolVersion(int protocolVersion) => protocolVersion switch
    {
        // Sherman (1), Abrams (2), Sherman S (3), Patton (4) — версии железа 0010..0040, каталог
        // производителя говорит про них `continuousSoftHardSet: false`.
        >= 1 and <= 4 => RideModeScale.ThreePosition,

        // Lynx (5), Sherman L (6), Patton S (7) — каталог говорит `true`. Oryx (8), Lynx S (9),
        // Nosfet (42, 43, 44) и всякая версия новее нашей таблицы — по умолчанию тоже плавные.
        // Ноль сюда же: до первого кадра телеметрии версии нет вовсе (VeteranDecoder.IsReady), и
        // это ровно тот случай «поколение определить не удалось», ради которого умолчание и завели.
        _ => RideModeScale.Continuous,
    };
}
