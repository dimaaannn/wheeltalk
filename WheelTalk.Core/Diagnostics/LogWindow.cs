using System.Globalization;

namespace WheelTalk.Core.Diagnostics;

/// <summary>
/// Срез ленты журнала за последние сутки — то, что уходит по кнопке «Полный журнал» (решение
/// владельца 15.08.2026).
/// <para>
/// <b>Зачем понадобилось.</b> В комплект диагностики идёт <c>diagnostics.log</c> — склейка
/// получасовых выжимок, и между ними суточные дыры. Разбор заморозки 15.08.2026 упёрся ровно в
/// это: полная лента (<c>wheeltalk.log</c> и её прошлое поколение) всё время лежала рядом, но
/// наружу не выходила. Целиком её отдавать незачем — четыре мегабайта на два поколения, — а сутки
/// закрывают любой разбор «что было вчера вечером».
/// </para>
/// <para>
/// <b>Здесь чистая логика и ничего платформенного</b>: строки приходят потоком, ответ уходит
/// потоком. Файлы читает android-часть, а решение «эта строка входит в срез» проверяется числами.
/// </para>
/// </summary>
public static class LogWindow
{
    /// <summary>
    /// Глубина среза. Сутки — слово владельца 15.08.2026: этого хватает на «вчера вечером
    /// приложение вело себя странно» и не хватает, чтобы превратить пересылку в выгрузку. Менять
    /// только его же словом.
    /// </summary>
    public static readonly TimeSpan Window = TimeSpan.FromHours(24);

    /// <summary>Длина метки времени в строке журнала: «2026-08-15 01:30:07.123».</summary>
    private const int StampLength = 23;

    /// <summary>Формат метки — тот, которым пишет <c>FileLog</c>. Второго формата у ленты нет.</summary>
    private const string StampFormat = "yyyy-MM-dd HH:mm:ss.fff";

    /// <summary>
    /// Строки за последние <see cref="Window"/> от <paramref name="now"/>, по порядку.
    /// <para>
    /// <b>Строка без метки идёт со своей.</b> Стек исключения и всякое продолжение пишутся
    /// отдельными строками без времени: оторви их от строки, за которой они стоят, — и в срез
    /// попадёт заголовок исключения без самого исключения, то есть худшее из возможного для
    /// разбора. Поэтому продолжение наследует решение последней строки с меткой.
    /// </para>
    /// <para>
    /// <b>До первой метки — не берём.</b> Такие строки принадлежат записи, которой в этих файлах
    /// уже нет (её унесла ротация), и отнести их не к чему.
    /// </para>
    /// <para>
    /// <b>Верхней границы нет.</b> Метка из будущего — это переведённые часы телефона, а не мусор:
    /// выбросив её, мы потеряли бы строки вокруг того самого мгновения, ради которого срез и берут.
    /// </para>
    /// </summary>
    /// <param name="lines">Лента по порядку: сперва прошлое поколение файла, затем нынешнее.</param>
    /// <param name="now">Местное время «сейчас» — тем же стенным часам, что и метки в ленте.</param>
    public static IEnumerable<string> Tail(IEnumerable<string> lines, DateTime now)
    {
        DateTime since = now - Window;
        bool taking = false;

        foreach (string line in lines)
        {
            if (Stamp(line) is { } stamp) taking = stamp >= since;

            if (taking) yield return line;
        }
    }

    /// <summary>
    /// Метка времени строки либо <c>null</c>, если строка — продолжение. Разбирается ровно начало
    /// строки: искать метку внутри значило бы принять за неё дату из текста сообщения.
    /// </summary>
    public static DateTime? Stamp(string line)
    {
        if (line.Length < StampLength) return null;

        return DateTime.TryParseExact(
            line.AsSpan(0, StampLength),
            StampFormat,
            CultureInfo.InvariantCulture,
            DateTimeStyles.None,
            out var stamp)
            ? stamp
            : null;
    }
}
